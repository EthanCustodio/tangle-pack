def compute_pseudoneighbors(
    trellis: "Trellis",
    *,
    collision_rtol: float = 1e-2,
) -> list[PseudoneighborPair]:
    """
    Find the reference pseudoneighbor pairs (pure query).

    Implements Compute-Pseudoneighbors(T): walk the consecutive intersection
    pairs of the SINGLE reference window W^S(r_n, r_{n+p}) toward the anchor
    and keep each pair neither of whose open intervals, the unstable one
    W^U(x0, x1) and the stable one W^S(x0, x1), holds a point of X: a trellis
    intersection or any iterate of one.

    There is one reference window per fixed point, not one per branch: r_n is
    the chosen strong pip itself (the intersection with the globally greatest
    stable canonical distance once the manifold is cut at the pip and its
    forward iterates), so only the pip's own branch carries the window. On a
    period-k orbit every pseudoneighbor trajectory makes its first (outermost)
    appearance inside that single window; the appearances on the other
    branches are its forward iterates — generated by
    :func:`extend_pseudoneighbor_trajectories`, never as independent
    references (walking each branch's window would find every trajectory k
    times and collide). The check set N is the trellis's own crossings, cut at
    the pip orbit when a pip is chosen (``Trellis.cut_at_pip_orbit``). Without
    a chosen strong pip the globally outermost intersection plays r_n.

    Args:
        trellis: The Trellis to read intersections and eigen/orbit data from.
        collision_rtol: Relative slack of the 2D endpoint-collision test that
            recognises the pair's own (noisy) endpoint iterates so they never
            disqualify it (both cdists must match an endpoint).

    Returns:
        The reference pairs (``is_reference=True``), from the outermost pair
        toward the anchor (per fixed point of the trellis). A fixed point whose
        r_{n+p} = M^p(r_n) is not in the iterate table gets none (WARNING).
    """
    candidates = trellis.own_intersection_ids
    pairs: list[PseudoneighborPair] = []

    for fixed_point in trellis.fixed_points:
        branch, r_n = _reference_branch(trellis, fixed_point)
        if branch is None or len(branch) < 2:
            logger.warning(
                "No usable reference window for %r; skipping", fixed_point
            )
            continue

        r_end = trellis.iterate(r_n, branch.return_period)
        if r_end is None or trellis.intersection(r_end).manifold_b_key != branch.key:
            logger.warning(
                "Stable branch %s: r_{n+p} = M^%d(%d) is not in the iterate table; "
                "skipping (trellis too small for a full reference window?)",
                branch.key,
                branch.return_period,
                r_n,
            )
            continue

        x0 = r_n
        x1 = trellis.next_intersection(x0, "stable", toward_anchor=True)
        while x0 != r_end:
            if x1 is None:
                logger.warning(
                    "Stable branch %s ran out of intersections before r_{n+p}",
                    branch.key,
                )
                break
            if all(
                _interval_is_clear(trellis, x0, x1, stability, candidates, collision_rtol)
                for stability in ("unstable", "stable")
            ):
                pair = PseudoneighborPair(
                    x0, x1, branch_key=branch.key, is_reference=True, iterate=0
                )
                pair.origin = pair.as_tuple()
                pairs.append(pair)
            x0 = x1
            x1 = trellis.next_intersection(x1, "stable", toward_anchor=True)

    logger.debug("Found %d reference pseudoneighbor pair(s)", len(pairs))
    return pairs


def extend_pseudoneighbor_trajectories(
    trellis: "Trellis",
    references: Iterable[PseudoneighborPair],
) -> list[PseudoneighborPair]:
    """
    Generate the full pseudoneighbor trajectories from the reference pairs.

    Each reference pair is mapped forward and backward one step at a time
    through the iterate table, emitting a pair per step until a member's image
    is no crossing of the trellis (unregistered, or past its pip-orbit cut: a
    pair never leaves T(q0)). Forward pairs are recorded (they are real
    pairs) but never holed: holes propagate backward only, on every branch of
    a period-k orbit (``StablePartition._is_forward_iterate``).

    Args:
        trellis: The Trellis whose iterate table to walk.
        references: Reference pairs from :func:`compute_pseudoneighbors`.

    Returns:
        The generated pairs (``is_reference=False``), deduplicated against the
        references and against each other.
    """
    references = list(references)
    seen = {ref.as_tuple() for ref in references}
    out: list[PseudoneighborPair] = []

    for ref in references:
        for direction in (1, -1):
            a, b = ref.intersection_a, ref.intersection_b
            for steps in count(1):
                a, b = trellis.iterate(a, direction), trellis.iterate(b, direction)
                if a not in trellis or b not in trellis:
                    break
                key = (min(a, b), max(a, b))
                if key in seen:
                    # The table is injective, so a collision means the rest of
                    # the chain coincides too.
                    break
                seen.add(key)
                branch_key = trellis.intersection(a).manifold_b_key
                if trellis.intersection(b).manifold_b_key != branch_key:
                    logger.warning(
                        "Iterated pair (%d, %d) landed on different stable "
                        "branches; the iterate table may be inconsistent",
                        a,
                        b,
                    )
                out.append(
                    PseudoneighborPair(
                        a, b, branch_key=branch_key, is_reference=False,
                        iterate=direction * steps, origin=ref.as_tuple(),
                    )
                )

    logger.debug("Extended %d reference pair(s) into %d iterated pair(s)",
                 len(references), len(out))
    return out


def _branch_text(key: ManifoldKey) -> str:
    """A branch as the warnings print it: ``s(1.0)``, ``A:u(2.0)`` when lettered."""
    fixed_point, stability, orbit_index, branch_index = key
    text = f"{stability[0]}({orbit_index}.{branch_index})"
    return text if fixed_point.label is None else f"{fixed_point.label}:{text}"


def _reference_branch(
    trellis: "Trellis", fixed_point: "FixedPoint"
) -> tuple[Optional["TrellisBranch"], Optional[int]]:
    """The fixed point's single reference branch and its r_n.

    The branch of the pip the trellis is cut at for this fixed point — only
    that branch carries the reference window; the other branches are cut at the
    pip's iterates and their trajectory appearances come from extension.
    Without a pip, the branch holding the globally outermost intersection plays
    the same role.
    """
    pip = trellis.pips.get(fixed_point)
    if pip is not None:
        return trellis.branch(trellis.intersection(pip).manifold_b_key), pip

    best_branch, best_id, best_s = None, None, -math.inf
    for branch in trellis.branches_of(fixed_point, "stable"):
        if not len(branch):
            continue
        outer = branch.ordered_ids(toward_anchor=True)[0]
        s = trellis.intersection(outer).stable_cdist
        if s > 0.0 and s > best_s:
            best_branch, best_id, best_s = branch, outer, s
    if best_branch is not None:
        logger.info(
            "No strong pip on %r; reference window starts at its globally "
            "outermost intersection %s",
            fixed_point,
            best_id,
        )
    return best_branch, best_id


def _interval_is_clear(
    trellis: "Trellis",
    x0: int,
    x1: int,
    stability: Stability,
    candidates: Iterable[int],
    collision_rtol: float,
) -> bool:
    """True if no trellis intersection (or iterate of one) lies on the open
    ``stability`` interval between x0 and x1.

    Iterates over ALL n in Z (the definition's X uses the full orbit): a
    backward iterate counts even when it lands on the removed stable tail —
    e.g. the preimages of blasted crossings puncture the interval they land
    on, per the author. Each landing is resolved by iterate-table LOOKUP
    first (``Trellis.iterate``): a linked landing is a registered crossing,
    so its identity (is it x0 or x1?) and its cdist are exact. An unlinked
    landing is read in r's own frame when the table knows an image of x0 or
    x1 there: r punctures iff its registered cdist lies strictly between the
    pair's images (one may be placed by ``image_cdist``, and an r that
    2D-collides with a placed end is that endpoint's own orbit). Only when
    neither image is registered is the landing placed by scaling (both cdists
    by ``Trellis.image_cdist``'s factors). There the open interval is strict
    and the landing is skipped only when it 2D-collides with an endpoint (both
    the scaled unstable and stable positions match within ``collision_rtol``)
    — x0/x1's own orbit up to cdist noise, ``Trellis.same_point``.

    The arc is the pair's ``stability`` arc, so the cycle, ``k`` and ``beta``
    are those of ITS fixed point: A's for the unstable arc of a heteroclinic
    pair of ``W^u(A)`` crossings on B's stable branch, B's for its stable arc.
    Both 2D collisions compare the OTHER side's cdists too, so they skip
    only an r whose other side lies on the pair's other-side fixed point.
    """
    ix0, ix1 = trellis.intersection(x0), trellis.intersection(x1)
    arc_key = attrgetter("manifold_a_key" if stability == "unstable" else "manifold_b_key")
    other_key = attrgetter("manifold_b_key" if stability == "unstable" else "manifold_a_key")
    cdist = attrgetter(f"{stability}_cdist")
    other = "stable" if stability == "unstable" else "unstable"

    def point(value: float, other_value: float) -> tuple[float, float]:
        """``(value, other_value)`` as ``same_point`` reads it: (unstable, stable)."""
        return (value, other_value) if stability == "unstable" else (other_value, value)

    key = arc_key(ix0)
    if stability == "stable":
        assert key == arc_key(ix1), "the walk steps along one stable branch"
    elif key is None or key != arc_key(ix1):
        return False  # no single unstable arc connects the pair (see Dev Notes)

    owner = key[0]
    pos_map, k = owner.branch_position_map(stability)
    beta = owner.per_step_beta(stability)  # < 1 for the stable arc: image_cdist's factor
    pos_target = pos_map[key]

    lo, hi = sorted((cdist(ix0), cdist(ix1)))
    if hi == lo or lo <= 0.0:
        return False  # degenerate interval (near-tangency or anchor endpoint)
    endpoints = [(ix.unstable_cdist, ix.stable_cdist) for ix in (ix0, ix1)]

    def log_puncture(r_id: int, steps: int, reading: str, value: float, ends: tuple) -> None:
        logger.debug(
            "Pair (%d, %d): %s interval punctured by %d at M^%d, %s reading "
            "(cdist %.9g in (%.9g, %.9g))",
            x0, x1, stability, r_id, steps, reading, value, *ends,
        )

    lap = beta**k  # one branch return: k map steps
    log_lap = k * math.log(beta)
    for r_id in candidates:
        if r_id == x0 or r_id == x1:
            continue
        r = trellis.intersection(r_id)
        if cdist(r) <= 0.0:
            continue  # the anchor: no position along any branch

        pos_r = pos_map.get(arc_key(r))
        if pos_r is None:
            continue  # foreign manifold: never lands on this branch
        # A 2D endpoint collision compares the other side's cdists too, so only
        # an r whose other side is the pair's fixed point's can be an
        # endpoint's orbit.
        same_other = other_key(r)[0] is other_key(ix0)[0]
        d = (pos_target - pos_r) % k
        c = cdist(r) * beta**d
        # After d + m*k total steps the cdist is c * lap^m; only finitely many
        # integers m can put it inside (lo, hi). The bounds swap when beta < 1.
        bounds = (math.log(lo / c) / log_lap, math.log(hi / c) / log_lap)
        for m in range(math.floor(min(bounds)), math.ceil(max(bounds)) + 1):
            value = c * lap**m
            if not (lo < value < hi):
                continue
            steps = d + m * k

            # Lookup first: when the iterate table knows M^steps(r), the
            # landing is a registered crossing and its identity and cdists
            # are exact. Only an unlinked landing is placed by scaling.
            landing = trellis.iterate(r_id, steps)
            if landing is not None:
                if landing == x0 or landing == x1:
                    continue  # the endpoint itself, by the table
                z = trellis.intersection(landing)
                if arc_key(z) != key:
                    logger.warning(
                        "Iterate table maps %d by %d steps to %d on %s "
                        "branch %s, not the pair's branch %s; ignoring it",
                        r_id, steps, landing, stability, arc_key(z), key,
                    )
                    continue
                if lo < cdist(z) < hi:
                    log_puncture(r_id, steps, "table", cdist(z), (lo, hi))
                    return False
                continue

            # Lookup first on the pair's side too: the images of x0 and x1 bound
            # the image of the interval on r's own branch, where r's registered
            # cdist is exact.
            images = [trellis.iterate(x, -steps) for x in (x0, x1)]
            if any(image is not None for image in images):
                ends = []
                for x, image in zip((x0, x1), images):
                    if image is not None:
                        ends.append(cdist(trellis.intersection(image)))
                        continue
                    _, c_e, _ = trellis.image_cdist(x, -steps, stability)
                    _, o_e, _ = trellis.image_cdist(x, -steps, other)
                    if same_other and same_point(
                        r.unstable_cdist, r.stable_cdist, *point(c_e, o_e), collision_rtol
                    ):
                        continue  # r is x's own unlinked orbit (2D collision)
                    ends.append(c_e)
                if r_id in images or len(ends) < 2:
                    continue  # an endpoint itself, or its own unlinked orbit
                lo_r, hi_r = sorted(ends)
                if lo_r < cdist(r) < hi_r:
                    log_puncture(r_id, steps, "own frame", cdist(r), (lo_r, hi_r))
                    return False
                continue

            _, other_value, _ = trellis.image_cdist(r_id, steps, other)
            if same_other and any(
                same_point(*point(value, other_value), u_e, s_e, collision_rtol)
                for u_e, s_e in endpoints
            ):
                continue  # the endpoint's own orbit (2D collision)
            log_puncture(r_id, steps, "scaled", value, (lo, hi))
            return False
    return True
