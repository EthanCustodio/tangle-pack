"""
Compute-Pseudoneighbors: the pseudoneighbor pairs of a trellis.

Finds the reference pseudoneighbor pairs on a fixed point's reference window
and extends them to their full trajectories under the map.

Dev Notes — Compute-Pseudoneighbors (Pseudoneighbor_Algorithm.pdf)

Two intersections x, x' are a pseudoneighbor pair iff the open stable interval
W^S(x, x') and the open unstable interval W^U(x, x') contain no trellis
intersection nor any iterate M^n (n in Z) of one. For a finite trellis every
pair first appears on the reference window W^S(r_n, r_{n+p}), where r_n is the
end of the stable manifold and p = the branch return period; the pairs found
there are the *reference* pseudoneighbors, and the full trajectories are their
iterates (extend_pseudoneighbor_trajectories).

There is ONE reference window per fixed point, on the chosen strong pip's own
branch, with r_n = the pip itself. The PDF states this subtly: r_n is "THE
intersection with the greatest stable canonical distance" (globally, not per
branch) and it is sufficient to check only that interval. Why it works for a
period-k orbit: the manifold is cut at the pip (cdist c on its branch) and at
the pip's forward iterates on the other branches (c/beta, c/beta^2, ...), and
a pseudoneighbor trajectory walked backward multiplies its stable cdist by
beta per step while cycling branches — so its position RELATIVE to the local
cut is constant within a lap and jumps by beta**k exactly once per lap, at
the pip's branch. Every trajectory therefore makes its outermost appearance
inside the single window W^S(pip, M^k(pip)); its appearances on the other
branches are the +1 .. +(k-1) forward iterates, generated by
extend_pseudoneighbor_trajectories. Walking each branch's window (the k=1
extrapolation) finds every trajectory k times and treats each copy as an
independent reference — colliding hole propagations (author-reported bug).
N is the trellis's: choosing the pip cuts the trellis to T(q0), its stable
branches at the pip's orbit and its unstable branches at the deepest
registered point of that orbit (``Trellis.cut_at_pip_orbit``, D10 and D12), so
a crossing past a cut is a point of X here, never of N. Without a chosen
strong pip, the globally outermost intersection plays r_n.

Implementation notes:

* p = branch.return_period = k_value: a branch return is k_value map steps
  and scales a canonical distance by beta**k_value (= |lambda_u|**num_branches,
  lambda_u squared under inversion; INV-2, fixed in WP2). The inversion
  ordering (k_value == 2*period) is exercised by the inversion law cases (the
  k=4 saddle and the k=4.1 period-2 orbit).
* The iterate table is the only identity authority: r_{n+p} and every
  trajectory image are table lookups (Trellis.iterate). Since WP2 the table is
  filled by an exact rule after every detection and blast, so a missing link
  is a missing image CROSSING, never a match to be made here by cdist.
* Period-k gaps (D5, WP5). A period-k chain is grown one map step at a time,
  so its unstable branches are staggered: each reaches beta further than the
  one before it in the cycle. A reference on the outermost lap of the longest
  branch therefore has no computed +j image (inversion: the +1 image of the
  window pair lies at unstable cdist 55.5 on u(0.0), whose last crossing is
  at 13.2; p3 at 6 blasts: 4097 against 1662), and its appearance on
  that branch is not in the trellis. extend_pseudoneighbor_trajectories names
  every stable branch left without it in ONE WARNING per branch, with each
  missing member's image_cdist prediction; nothing is matched or invented.
  Walking the other branches' windows instead finds "orphan" pairs there, but
  their open stable interval holds the predicted images of the tip crossings,
  so they are no pairs by the definition (they pass only because the
  stable-side check reads registered crossings alone, NUM-18). Filling the
  gap is DEC-19 (WP5 slice 2).
* The trellis is cut at the pip orbit (``Trellis.cut_at_pip_orbit``): a
  missing pip iterate is PLACED there by ``image_cdist`` and flagged in one
  WARNING (PK-6), never left uncut. A trajectory is extended only while its
  images are crossings of the trellis: one leaving T(q0) is a pair of X, not
  of N (its appearance on that branch is a gap, named like the stagger).
* The algorithm walks *consecutive* intersections on the stable branch, so the
  open stable interval between a candidate pair is empty by construction; all
  the work is in the unstable-interval check.
* Both members of a pair must lie on the SAME unstable branch: two distinct
  unstable curves (different orbit points, or the two inversion half-branches,
  which join only through their one anchor — itself a trellis point) cannot be
  connected by an open unstable arc, so such a pair is rejected outright.
* Heteroclinic pairs (D7, WP9). Two consecutive crossings of ``W^u(A)`` on B's
  stable branch are a pair of B's tangle when the arc between them is clear.
  The arc is A's, so it is tested with A's branch cycle, ``k`` and ``beta``,
  against the crossings whose unstable side is A's (A x A and A x B; B's
  unstable crossings never land on A's unstable manifold). The pair needs a
  trellis holding both tangles: a tangle's own trellis holds no heteroclinic
  crossing (``Trellis.from_workbench``), so the session runs this stage on the
  selection's trellis.
* One map step scales an unstable canonical distance by
  FixedPoint.per_step_beta("unstable") = |lambda_u|^(1/period); a crossing's
  unlinked landing is placed by Trellis.image_cdist, the one crossing-level
  scaling path. Both count MAP STEPS.
* The all-iterates membership test is closed-form, not a loop over n: a
  candidate r on unstable branch at cycle position pos_r lands on the target
  branch only for step counts n = d + m*k, d = (pos_target - pos_r) mod k,
  where its unstable cdist becomes r_u * beta^d * (beta^k)^m. Since
  beta > 1, only finitely many m put that inside the open interval
  (lo, hi); the m-range comes from log ratios and each candidate m is then
  tested against the strict inequalities directly.
* Lookup before scaling. A landing M^steps(r) is first resolved through the
  iterate table (Trellis.iterate composes the +/-1 links); a linked landing
  is a registered crossing, so "is it x0 or x1?" and its unstable cdist are
  exact — no tolerance is involved. Only when the table has no chain is the
  landing placed by scaling r's cdists (Trellis.image_cdist; the cdist
  definition, never the map). Why the order matters: registered cdists carry
  each crossing's own absolute positional noise, while a stable cdist shrinks
  by beta per step, so ANY relative tolerance on a scaled value fails at
  depth — the k=2.8 script at 8 blasts lost the pair (10, 9) to its own
  M^6(9), linked in the table but 1.8% off on the scaled stable cdist.
  Lookup comes first on the PAIR's side too (BCG-5, WP8): when the table
  knows an image M^-steps of x0 or x1, an unlinked r is compared with those
  images on r's OWN unstable branch (the image of an arc is an arc, cdist is
  monotone along one polyline), the other end placed by image_cdist. Only
  when neither image is registered is r scaled back onto the pair. Nested at
  10 outer blasts lost its only outer reference (37, 38) to scaling noise:
  crossing 592 sits 6178 below M^8(37) on its own polyline, outside the image
  of the pair, but its depth-8 scaled cdist landed 1.3e-5 inside (37, 38),
  where the scaling noise is 0.0103 (k32 at 12 blasts the same).
* For unlinked landings the open interval is STRICT; x0, x1 and their own
  iterates sit exactly at the (scaled) endpoints up to canonical-distance
  noise and are recognised by a 2D endpoint collision (both the landing's
  unstable AND stable positions match an endpoint within collision_rtol —
  the StrongPip same-point test; never the product). A blanket relative
  shrink of the interval was tried first and swallowed GENUINE interior
  crossings on deep blast levels, where interval widths are small relative
  to the cdist magnitude.
* Check set N = trellis.own_intersection_ids (the cut trellis), mirroring
  StrongPip's same-fixed-point restriction: a candidate whose unstable side
  belongs to a different fixed point than the PAIR'S ARC can never iterate onto
  that unstable manifold (its key is absent from the arc's branch cycle, so the
  position lookup drops it). The 2D endpoint collision of a scaled landing
  compares stable cdists, so it applies only to a candidate on the pair's own
  stable manifold (an A x A crossing's orbit stays on W^s(A), never x0's on
  W^s(B)). Every detected crossing carries both branch keys (Tangle asserts
  it). Landings stay RAW table lookups: X holds the iterates of N outside
  T(q0) too.
"""

