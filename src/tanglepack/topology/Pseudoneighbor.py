def forward_unstable_branch_cycle(fixed_point: "FixedPoint") -> list[ManifoldKey]:
    """
    Return the fixed point's unstable branches in forward-iteration (M) order.

    Thin wrapper around :meth:`FixedPoint.branch_cycle`, which is the single
    source of truth for the chain of manifold pieces one map step walks.

    Args:
        fixed_point: The fixed point whose unstable branches to order.

    Returns:
        List of manifold keys (fixed_point, "unstable", orbit_index,
        branch_index) in forward-iteration order, of length ``k_value``.
    """
    return fixed_point.branch_cycle("unstable")


def compute_pseudoneighbors(
    trellis: "Trellis",
    *,
    collision_rtol: float = 1e-2,
    tol: Optional[float] = None,
) -> list[PseudoneighborPair]:
    """
    Find the reference pseudoneighbor pairs (pure query).

    Implements Compute-Pseudoneighbors(T): walk the consecutive intersection
    pairs of the SINGLE reference window W^S(r_n, r_{n+p}) toward the anchor
    and keep each pair whose open unstable interval contains no trellis
    intersection nor any iterate of one.

    There is one reference window per fixed point, not one per branch: r_n is
    the chosen strong pip itself (the intersection with the globally greatest
    stable canonical distance once the manifold is cut at the pip and its
    forward iterates), so only the pip's own branch carries the window. On a
    period-k orbit every pseudoneighbor trajectory makes its first (outermost)
    appearance inside that single window; the appearances on the other
    branches are its forward iterates — generated by
    :func:`extend_pseudoneighbor_trajectories`, never as independent
    references (walking each branch's window would find every trajectory k
    times and collide). The check set N is the trellis's own crossings, cut at
    the pip orbit when a pip is chosen (``Trellis.cut_at_pip_orbit``). Without
    a chosen strong pip the globally outermost intersection plays r_n.

    Args:
        trellis: The Trellis to read intersections and eigen/orbit data from.
        collision_rtol: Relative slack of the 2D endpoint-collision test that
            recognises the pair's own (noisy) endpoint iterates so they never
            disqualify it (both cdists must match an endpoint).
        tol: Absolute canonical-distance slack used to recognise the anchor
            artifact. Defaults to the registry's ``cdist_tol``.

    Returns:
        The reference pairs (``is_reference=True``), from the outermost pair
        toward the anchor (per fixed point of the trellis). A fixed point whose
        r_{n+p} = M^p(r_n) is not in the iterate table gets none (WARNING).
    """
    if tol is None:
        tol = trellis.registry.cdist_tol

    candidates = trellis.own_intersection_ids
    pairs: list[PseudoneighborPair] = []

    for fixed_point in trellis.fixed_points:
        branch, r_n = _reference_branch(trellis, fixed_point, tol)
        if branch is None or len(branch) < 2:
            logger.warning(
                "No usable reference window for %r; skipping", fixed_point
            )
            continue

        r_end = trellis.iterate(r_n, branch.return_period)
        if r_end is None or trellis.intersection(r_end).manifold_b_key != branch.key:
            logger.warning(
                "Stable branch %s: r_{n+p} = M^%d(%d) is not in the iterate table; "
                "skipping (trellis too small for a full reference window?)",
                branch.key,
                branch.return_period,
                r_n,
            )
            continue

        x0 = r_n
        x1 = trellis.next_intersection(x0, "stable", toward_anchor=True)
        while x0 != r_end:
            if x1 is None:
                logger.warning(
                    "Stable branch %s ran out of intersections before r_{n+p}",
                    branch.key,
                )
                break
            if _unstable_interval_is_clear(
                trellis, x0, x1, candidates, collision_rtol, tol
            ):
                pair = PseudoneighborPair(
                    x0, x1, branch_key=branch.key, is_reference=True, iterate=0
                )
                pair.origin = pair.as_tuple()
                pairs.append(pair)
            x0 = x1
            x1 = trellis.next_intersection(x1, "stable", toward_anchor=True)

    logger.debug("Found %d reference pseudoneighbor pair(s)", len(pairs))
    return pairs


def extend_pseudoneighbor_trajectories(
    trellis: "Trellis",
    references: Iterable[PseudoneighborPair],
) -> list[PseudoneighborPair]:
    """
    Generate the full pseudoneighbor trajectories from the reference pairs.

    Each reference pair is mapped forward and backward one step at a time
    through the iterate table, emitting a pair per step until a member's image
    is no crossing of the trellis (unregistered, or past its pip-orbit cut: a
    pair never leaves T(q0)). On a period-k orbit this is what populates the OTHER
    branches: the reference window lives on the strong pip's branch only, and
    the trajectory's appearance on each remaining branch is its +1 .. +(k-1)
    forward iterate (D5).

    Args:
        trellis: The Trellis whose iterate table to walk.
        references: Reference pairs from :func:`compute_pseudoneighbors`.

    Returns:
        The generated pairs (``is_reference=False``), deduplicated against the
        references and against each other.

    Note:
        A forward walk that stops before ``+(k-1)`` leaves the remaining
        branches without this trajectory's appearance: its image crossings are
        not computed (the stagger of a period-k chain, see the Dev Notes) or lie
        past the trellis's pip-orbit cut.
        Nothing is invented for them; ONE WARNING per such stable branch names
        it, each reference missing it, and where ``image_cdist`` predicts the
        missing members on their unstable branch.
    """
    references = list(references)
    seen = {ref.as_tuple() for ref in references}
    out: list[PseudoneighborPair] = []
    gaps: dict[ManifoldKey, list[str]] = {}

    for ref in references:
        fixed_point = ref.branch_key[0]
        for direction in (1, -1):
            a, b = ref.intersection_a, ref.intersection_b
            for steps in count(1):
                a, b = trellis.iterate(a, direction), trellis.iterate(b, direction)
                if a not in trellis or b not in trellis:
                    if direction > 0:
                        for j in range(steps, fixed_point.k_value):
                            branch_key = fixed_point.advance_key(ref.branch_key, j)
                            gaps.setdefault(branch_key, []).append(
                                _missing_appearance(trellis, ref, j)
                            )
                    break
                key = (min(a, b), max(a, b))
                if key in seen:
                    # The table is injective, so a collision means the rest of
                    # the chain coincides too.
                    break
                seen.add(key)
                branch_key = trellis.intersection(a).manifold_b_key
                if trellis.intersection(b).manifold_b_key != branch_key:
                    logger.warning(
                        "Iterated pair (%d, %d) landed on different stable "
                        "branches; the iterate table may be inconsistent",
                        a,
                        b,
                    )
                out.append(
                    PseudoneighborPair(
                        a, b, branch_key=branch_key, is_reference=False,
                        iterate=direction * steps, origin=ref.as_tuple(),
                    )
                )

    for branch_key, missing in gaps.items():
        logger.warning(
            "Stable branch %s gets no window hole from %s: the image crossings are not "
            "crossings of the trellis (a period-k chain is grown one map step per "
            "branch, so the outermost lap of the longest unstable branch has no image, "
            "or the image lies past the pip-orbit cut); nothing is invented, grow or "
            "blast to register them (D5)",
            _branch_text(branch_key),
            "; ".join(missing),
        )
    logger.debug("Extended %d reference pair(s) into %d iterated pair(s)",
                 len(references), len(out))
    return out


def _missing_appearance(trellis: "Trellis", ref: PseudoneighborPair, j: int) -> str:
    """Why a reference has no ``+j`` appearance: where each unlinked member would land.

    The landing is ``image_cdist`` on the unstable side, set against the last
    crossing of that unstable branch in the trellis: past it is the stagger or
    the pip-orbit cut, inside it an image crossing the table does not link.
    """
    landings = []
    for end in ref.as_tuple():
        if trellis.iterate(end, j) in trellis:
            continue
        key, cdist, _ = trellis.image_cdist(end, j, "unstable")
        branch = trellis.branch(key)
        if branch is None or not branch.intersection_ids:
            where = "which has no crossing"
        else:
            last = trellis.intersection(branch.intersection_ids[-1]).unstable_cdist
            where = (
                f"past its last crossing at {last:.4g}" if cdist > last
                else f"inside its crossings (last at {last:.4g}) but unlinked"
            )
        landings.append(f"{end} -> {cdist:.4g} on {_branch_text(key)}, {where}")
    return f"reference {ref.as_tuple()} at +{j} ({', '.join(landings)})"


def _branch_text(key: ManifoldKey) -> str:
    """A branch as the warnings print it: ``s(1.0)``, ``A:u(2.0)`` when lettered."""
    fixed_point, stability, orbit_index, branch_index = key
    text = f"{stability[0]}({orbit_index}.{branch_index})"
    return text if fixed_point.label is None else f"{fixed_point.label}:{text}"


def _reference_branch(
    trellis: "Trellis", fixed_point: "FixedPoint", tol: float
) -> tuple[Optional["TrellisBranch"], Optional[int]]:
    """The fixed point's single reference branch and its r_n.

    The branch of the pip the trellis is cut at for this fixed point — only
    that branch carries the reference window; the other branches are cut at the
    pip's iterates and their trajectory appearances come from extension.
    Without a pip, the branch holding the globally outermost intersection plays
    the same role.
    """
    pip = trellis.pips.get(fixed_point)
    if pip is not None:
        return trellis.branch(trellis.intersection(pip).manifold_b_key), pip

    best_branch, best_id, best_s = None, None, -math.inf
    for branch in trellis.branches_of(fixed_point, "stable"):
        if not len(branch):
            continue
        outer = branch.ordered_ids(toward_anchor=True)[0]
        s = trellis.intersection(outer).stable_cdist
        if s > tol and s > best_s:
            best_branch, best_id, best_s = branch, outer, s
    if best_branch is not None:
        logger.info(
            "No strong pip on %r; reference window starts at its globally "
            "outermost intersection %s",
            fixed_point,
            best_id,
        )
    return best_branch, best_id


def _unstable_interval_is_clear(
    trellis: "Trellis",
    x0: int,
    x1: int,
    candidates: Iterable[int],
    collision_rtol: float,
    tol: float,
) -> bool:
    """True if no trellis intersection (or iterate of one) lies on W^U(x0, x1).

    Iterates over ALL n in Z (the definition's X uses the full orbit): a
    backward iterate counts even when it lands on the removed stable tail —
    e.g. the preimages of blasted crossings puncture the interval they land
    on, per the author. Each landing is resolved by iterate-table LOOKUP
    first (``Trellis.iterate``): a linked landing is a registered crossing,
    so its identity (is it x0 or x1?) and its unstable cdist are exact. An
    unlinked landing is read in r's own frame when the table knows an image
    of x0 or x1 there: r punctures iff its registered cdist lies strictly
    between the pair's images (one may be placed by ``image_cdist``, and an r
    that 2D-collides with a placed end is that endpoint's own orbit). Only
    when neither image is registered is the landing placed by scaling: its
    unstable cdist by ``beta ** steps``, its stable one by
    ``Trellis.image_cdist``. There the open interval is strict and the landing is
    skipped only when it 2D-collides with an endpoint (both the scaled
    unstable and stable positions match within ``collision_rtol``) — x0/x1's
    own orbit up to cdist noise, the same-point test StrongPip uses.

    The arc is the unstable arc of the pair, so the cycle, ``k`` and ``beta`` are
    those of ITS fixed point: A's for a heteroclinic pair of ``W^u(A)`` crossings
    on B's stable branch (D7).
    """
    ix0 = trellis.intersection(x0)
    ix1 = trellis.intersection(x1)

    u_key = ix0.manifold_a_key
    if u_key is None or u_key != ix1.manifold_a_key:
        return False  # no single unstable arc connects the pair (see Dev Notes)

    owner = u_key[0]
    cycle = forward_unstable_branch_cycle(owner)
    pos_map, k = {key: i for i, key in enumerate(cycle)}, len(cycle)
    beta = owner.per_step_beta("unstable")
    pos_target = pos_map[u_key]

    lo, hi = sorted((ix0.unstable_cdist, ix1.unstable_cdist))
    if hi - lo <= tol or lo <= 0.0:
        return False  # degenerate interval (near-tangency or anchor endpoint)
    endpoints = (
        (ix0.unstable_cdist, ix0.stable_cdist),
        (ix1.unstable_cdist, ix1.stable_cdist),
    )

    lap = beta**k  # one branch return: k map steps (INV-2)
    log_lap = k * math.log(beta)
    for r_id in candidates:
        if r_id == x0 or r_id == x1:
            continue
        r = trellis.intersection(r_id)
        if abs(r.stable_cdist) <= tol and abs(r.unstable_cdist) <= tol:
            continue  # the anchoring fixed point, not a transverse crossing
        if r.unstable_cdist <= tol:
            continue  # no meaningful position along any unstable branch

        pos_r = pos_map.get(r.manifold_a_key)
        if pos_r is None:
            continue  # foreign unstable manifold: never lands on this branch
        d = (pos_target - pos_r) % k
        c = r.unstable_cdist * beta**d
        # After d + m*k total steps the cdist is c * lap^m; only finitely many
        # integers m can put it inside (lo, hi).
        m_lo = math.floor(math.log(lo / c) / log_lap)
        m_hi = math.ceil(math.log(hi / c) / log_lap)
        for m in range(m_lo, m_hi + 1):
            value = c * lap**m
            if not (lo < value < hi):
                continue
            steps = d + m * k

            # Lookup first: when the iterate table knows M^steps(r), the
            # landing is a registered crossing and its identity and cdists
            # are exact. Only an unlinked landing is placed by scaling.
            landing = trellis.iterate(r_id, steps)
            if landing is not None:
                if landing == x0 or landing == x1:
                    continue  # the endpoint itself, by the table
                z = trellis.intersection(landing)
                if z.manifold_a_key != u_key:
                    logger.warning(
                        "Iterate table maps %d by %d steps to %d on unstable "
                        "branch %s, not the pair's branch %s; ignoring it",
                        r_id, steps, landing, z.manifold_a_key, u_key,
                    )
                    continue
                if lo < z.unstable_cdist < hi:
                    logger.debug(
                        "Pair (%d, %d) punctured by %d = M^%d(%d) "
                        "(registered cdist %.6g in (%.6g, %.6g))",
                        x0, x1, landing, steps, r_id, z.unstable_cdist, lo, hi,
                    )
                    return False
                continue

            # Lookup first on the pair's side too: the images of x0 and x1 bound
            # the image of W^U(x0, x1) on r's own polyline, where r's registered
            # cdist is exact.
            images = [trellis.iterate(x, -steps) for x in (x0, x1)]
            if any(image is not None for image in images):
                ends = []
                for x, image in zip((x0, x1), images):
                    if image is not None:
                        ends.append(trellis.intersection(image).unstable_cdist)
                        continue
                    _, u_e, _ = trellis.image_cdist(x, -steps, "unstable")
                    _, s_e, _ = trellis.image_cdist(x, -steps, "stable")
                    if (
                        abs(r.unstable_cdist - u_e) <= collision_rtol * u_e + tol
                        and abs(r.stable_cdist - s_e) <= collision_rtol * s_e + tol
                    ):
                        continue  # r is x's own unlinked orbit (2D collision)
                    ends.append(u_e)
                if r_id in images or len(ends) < 2:
                    continue  # an endpoint itself, or its own unlinked orbit
                lo_r, hi_r = sorted(ends)
                if lo_r < r.unstable_cdist < hi_r:
                    logger.debug(
                        "Pair (%d, %d) punctured by %d in its own frame "
                        "(cdist %.9g in (%.9g, %.9g))",
                        x0, x1, r_id, r.unstable_cdist, lo_r, hi_r,
                    )
                    return False
                continue

            _, s_value, _ = trellis.image_cdist(r_id, steps, "stable")
            if r.manifold_b_key[0] is ix0.manifold_b_key[0] and any(
                abs(value - u_e) <= collision_rtol * u_e + tol
                and abs(s_value - s_e) <= collision_rtol * s_e + tol
                for u_e, s_e in endpoints
            ):
                continue  # the endpoint's own orbit (2D collision on one stable manifold)
            logger.debug(
                "Pair (%d, %d) punctured by %d at residue %d, m=%d "
                "(scaled cdist %.6g in (%.6g, %.6g))",
                x0, x1, r_id, d, m, value, lo, hi,
            )
            return False
    return True
